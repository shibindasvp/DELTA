// In-memory cache for resolved pincodes
const pincodeCache = new Map();


export async function lookupPincode(rawPincode) {
    const pincode = String(rawPincode || "").trim();

    if (!/^[1-9][0-9]{5}$/.test(pincode)) {
        return {
            success: false,
            message: "Pincode must be a valid 6-digit number starting with digits 1-9."
        };
    }

    if (pincodeCache.has(pincode)) {
        return { success: true, ...pincodeCache.get(pincode) };
    }

    try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 1200);

        const response = await fetch(`https://api.postalpincode.in/pincode/${pincode}`, {
            signal: controller.signal
        });
        clearTimeout(timeoutId);

        if (response.ok) {
            const data = await response.json();
            if (Array.isArray(data) && data[0]?.Status === "Success" && data[0]?.PostOffice?.length > 0) {
                const po = data[0].PostOffice[0];
                const city = po.District || po.Division || po.Block || po.Name || "";
                const state = po.State || "";

                if (city && state) {
                    const result = { city, state, pincode };
                    pincodeCache.set(pincode, result);
                    return { success: true, ...result };
                }
            }
        }
    } catch {
    }

    const prefix3 = pincode.slice(0, 3);
    if (PINCODE_PREFIX_MAP[prefix3]) {
        const entry = PINCODE_PREFIX_MAP[prefix3];
        const result = { city: entry.city, state: entry.state, pincode };
        pincodeCache.set(pincode, result);
        return { success: true, ...result };
    }

    const prefix2 = pincode.slice(0, 2);
    if (PINCODE_2DIGIT_MAP[prefix2]) {
        const entry = PINCODE_2DIGIT_MAP[prefix2];
        const result = { city: entry.city, state: entry.state, pincode };
        pincodeCache.set(pincode, result);
        return { success: true, ...result };
    }

    return {
        success: false,
        message: "Invalid or unrecognized pincode."
    };
}
